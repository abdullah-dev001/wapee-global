create table public.sms_credit_ledger (
  id bigint generated always as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  kind text not null check (kind in ('purchase', 'adjustment', 'debit', 'refund')),
  amount bigint not null,
  balance_after bigint not null check (balance_after >= 0),
  -- No FK: outbox rows are purged after 30 days and the ledger is append-only.
  outbox_id uuid,
  attempt integer,
  ref_ledger_id bigint references public.sms_credit_ledger(id),
  dial_code text,
  segments integer,
  encoding text,
  note text check (char_length(note) <= 300),
  created_by uuid,
  created_at timestamptz not null default now(),
  constraint sms_credit_ledger_sign check (
    (kind in ('debit') and amount < 0)
    or (kind in ('purchase', 'refund') and amount > 0)
    or (kind = 'adjustment' and amount <> 0))
);
create index sms_credit_ledger_business_idx on public.sms_credit_ledger (business_id, created_at desc);
create index sms_credit_ledger_outbox_idx on public.sms_credit_ledger (outbox_id);
create index sms_credit_ledger_ref_idx on public.sms_credit_ledger (ref_ledger_id);
-- One debit per outbox attempt; one refund per debit.
create unique index sms_credit_ledger_one_debit on public.sms_credit_ledger (outbox_id, attempt) where kind = 'debit';
create unique index sms_credit_ledger_one_refund on public.sms_credit_ledger (ref_ledger_id) where kind = 'refund';

alter table public.sms_credit_ledger enable row level security;
create policy sms_credit_ledger_select on public.sms_credit_ledger
  for select to authenticated
  using (public.is_super_admin() or public.has_permission(business_id, null, 'sms.send'));
grant select on public.sms_credit_ledger to authenticated;
grant all on public.sms_credit_ledger to service_role;

-- Append-only, except when the business itself is being deleted.
create or replace function public.enforce_sms_ledger_append_only()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.businesses b where b.id = old.business_id) then
    return old;  -- the tenant is going: let the cascade through
  end if;
  raise exception 'sms_credit_ledger is append-only' using errcode = '23514';
end $$;
revoke all on function public.enforce_sms_ledger_append_only() from public, anon, authenticated;
create trigger sms_credit_ledger_no_update before update or delete on public.sms_credit_ledger
  for each row execute function public.enforce_sms_ledger_append_only();

