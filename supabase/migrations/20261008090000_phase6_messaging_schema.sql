-- ---------------------------------------------------------------------------
-- message_outbox
-- ---------------------------------------------------------------------------
create table public.message_outbox (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  branch_id uuid not null references public.branches(id) on delete cascade,
  appointment_id uuid references public.appointments(id) on delete cascade,
  client_id uuid references public.clients(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  review_request_id uuid references public.review_requests(id) on delete cascade,
  channel text not null check (channel in ('email', 'sms', 'push')),
  event text not null check (event in (
    'booking_confirmed', 'pending_received', 'reminder', 'rescheduled', 'cancelled',
    'manage_link', 'review_request',
    'staff_new_booking', 'staff_pending_approval', 'staff_cancelled', 'staff_reminder')),
  status text not null default 'pending'
    check (status in ('pending', 'sending', 'retry', 'sent', 'dead', 'skipped', 'cancelled')),
  idempotency_key text not null unique check (char_length(idempotency_key) between 1 and 200),
  deliver_after timestamptz not null default now(),
  attempts integer not null default 0,
  max_attempts integer not null default 5,
  locked_until timestamptz,
  -- Set when an SMS debit was taken for the current attempt (the provider call is
  -- about to happen). A stale lock with this set is NOT retried: it may have sent.
  provider_call_at timestamptz,
  last_error text check (char_length(last_error) <= 300),
  -- Encrypted raw token (manage / review link). See the header.
  sealed bytea,
  -- Non-PII extras only (e.g. the old start time for a reschedule).
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  claimed_at timestamptz,
  sent_at timestamptz,
  finished_at timestamptz,
  constraint message_outbox_push_shape check (
    (channel = 'push') = (user_id is not null)
    and (channel = 'push') = (event like 'staff\_%')
    and (channel <> 'push') = (client_id is not null)),
  -- The token must not outlive the send.
  constraint message_outbox_sealed_only_while_open check (
    sealed is null or status in ('pending', 'sending', 'retry')),
  constraint message_outbox_payload_no_token check (not (payload ? 'token'))
);
create index message_outbox_due_idx on public.message_outbox (deliver_after) where status in ('pending', 'retry');
create index message_outbox_sending_idx on public.message_outbox (locked_until) where status = 'sending';
create index message_outbox_business_idx on public.message_outbox (business_id, channel, claimed_at);
create index message_outbox_branch_idx on public.message_outbox (branch_id);
create index message_outbox_appointment_idx on public.message_outbox (appointment_id);
create index message_outbox_client_idx on public.message_outbox (client_id);
create index message_outbox_user_idx on public.message_outbox (user_id);
create index message_outbox_review_request_idx on public.message_outbox (review_request_id);
create trigger message_outbox_updated_at before update on public.message_outbox
  for each row execute function public.set_updated_at();

alter table public.message_outbox enable row level security;
create policy message_outbox_super_admin on public.message_outbox
  for select to authenticated using (public.is_super_admin());
grant select on public.message_outbox to authenticated;
grant all on public.message_outbox to service_role;

-- ---------------------------------------------------------------------------
-- messages (the log)
-- ---------------------------------------------------------------------------
create table public.messages (
  id bigint generated always as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  branch_id uuid references public.branches(id) on delete cascade,
  outbox_id uuid references public.message_outbox(id) on delete set null,
  appointment_id uuid references public.appointments(id) on delete set null,
  channel text not null check (channel in ('email', 'sms', 'push')),
  event text not null,
  -- HMAC-SHA256 (Vault key) of the normalised address; and a masked display form.
  recipient_hash text,
  recipient_masked text,
  status text not null check (status in ('sent', 'failed', 'skipped')),
  code text,
  provider text,
  provider_id text,
  encoding text,
  segments integer,
  credits integer,
  error text check (char_length(error) <= 300),
  created_at timestamptz not null default now()
);
create index messages_business_idx on public.messages (business_id, created_at desc);
create index messages_branch_idx on public.messages (branch_id);
create index messages_outbox_idx on public.messages (outbox_id);
create index messages_appointment_idx on public.messages (appointment_id);
create index messages_recipient_sent_idx on public.messages (recipient_hash, created_at) where status = 'sent';

alter table public.messages enable row level security;
-- Owners (settings.business) and the super admin read the log. Nobody writes it
-- except the DEFINER functions.
create policy messages_select on public.messages
  for select to authenticated
  using (public.is_super_admin() or public.can(business_id, branch_id, 'settings.business'));
grant select on public.messages to authenticated;
grant all on public.messages to service_role;

