-- Phase 6A (notifications backend), part 1: schema.
--
-- WHAT THIS ADDS
--   * pg_net (so pg_cron can call the worker Edge Function) + three Vault keys
--   * notification_settings   per-branch: reminders, SMS on/off, quiet hours
--   * message_outbox          the queue. Rows are written in the SAME transaction
--                             as the business action; an Edge worker sends them.
--   * messages                the log. Masked recipient + HMAC hash, never a body,
--                             never a raw token, never a full link.
--   * message_suppressions    opt-outs (reminders / review requests only)
--   * push_tokens             Expo push tokens of business users
--   * messaging_limits        abuse caps, tunable without a deploy
--   * sms_country_rates / sms_credit_accounts / sms_credit_ledger
--   * appointments.scheduled_at   when the current time slot was chosen
--
-- TOKEN HANDLING (decided with the user): the raw manage / review token is sealed
-- (pgp_sym_encrypt, key in Supabase Vault) into message_outbox.sealed in the same
-- transaction as the action, and nulled the moment the row is sent / dead /
-- cancelled / skipped (a CHECK enforces it) or after 48 h (cron).
--
-- Every table has RLS ON. anon gets nothing. Writes are DEFINER functions only.

-- ---------------------------------------------------------------------------
-- Extensions and keys
-- ---------------------------------------------------------------------------
create extension if not exists pg_net;

do $$
declare
  v_name text;
begin
  foreach v_name in array array['outbox_seal_key', 'message_hash_key', 'outbox_worker_token'] loop
    if not exists (select 1 from vault.secrets where name = v_name) then
      perform vault.create_secret(
        pg_catalog.encode(extensions.gen_random_bytes(32), 'hex'),
        v_name,
        'Generated by the Phase 6A migration. Never leaves the database.'
      );
    end if;
  end loop;
end $$;

-- pg_net's schema `net` is owned by supabase_admin and its functions are
-- executable by anon/authenticated, and `postgres` cannot revoke that. Unlike
-- dblink this is NOT reachable: PostgREST exposes only `public` and
-- `graphql_public`, so `POST /rest/v1/rpc/http_post` with Content-Profile: net
-- answers 406 PGRST106 "Invalid schema: net" (checked against the live project,
-- 2026-10-08). The one rule that keeps it so: NO function in `public` that the
-- API roles can execute may call net.*. Only invoke_outbox_worker() does, and it
-- has no API grant (asserted in the test suite).

-- ---------------------------------------------------------------------------
-- appointments.scheduled_at: when the current time slot was chosen. The reminder
-- job uses it to avoid reminding about a booking made after the reminder time.
-- ---------------------------------------------------------------------------
alter table public.appointments
  add column if not exists scheduled_at timestamptz not null default now();

create or replace function public.touch_appointment_scheduled_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and new.starts_at is distinct from old.starts_at then
    new.scheduled_at := now();
  end if;
  return new;
end $$;
revoke all on function public.touch_appointment_scheduled_at() from public, anon, authenticated;

drop trigger if exists appointments_touch_scheduled_at on public.appointments;
create trigger appointments_touch_scheduled_at
  before update of starts_at on public.appointments
  for each row execute function public.touch_appointment_scheduled_at();

-- ---------------------------------------------------------------------------
-- notification_settings (one row per branch, created by trigger)
-- ---------------------------------------------------------------------------
create table public.notification_settings (
  branch_id uuid primary key references public.branches(id) on delete cascade,
  business_id uuid not null references public.businesses(id) on delete cascade,
  reminders_enabled boolean not null default true,
  reminder_hours_before integer not null default 24
    constraint notification_settings_reminder_hours check (reminder_hours_before between 1 and 72),
  -- "SMS enabled by the business": SMS is only ever used when this is on.
  sms_enabled boolean not null default false,
  review_requests_enabled boolean not null default true,
  -- Minutes from local midnight. Default 21:00-08:00. Equal values = no quiet hours.
  quiet_start_minute integer not null default 1260
    constraint notification_settings_quiet_start check (quiet_start_minute between 0 and 1439),
  quiet_end_minute integer not null default 480
    constraint notification_settings_quiet_end check (quiet_end_minute between 0 and 1439),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index notification_settings_business_idx on public.notification_settings (business_id);
create trigger notification_settings_updated_at before update on public.notification_settings
  for each row execute function public.set_updated_at();

create or replace function public.enforce_notification_settings_tenant()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.branches b where b.id = new.branch_id and b.business_id = new.business_id) then
    raise exception 'notification_settings: branch does not belong to that business' using errcode = '23514';
  end if;
  if tg_op = 'UPDATE' and (new.branch_id <> old.branch_id or new.business_id <> old.business_id) then
    raise exception 'notification_settings: branch and business cannot change' using errcode = '23514';
  end if;
  return new;
end $$;
revoke all on function public.enforce_notification_settings_tenant() from public, anon, authenticated;
create trigger notification_settings_tenant before insert or update on public.notification_settings
  for each row execute function public.enforce_notification_settings_tenant();

create or replace function public.create_default_notification_settings()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.notification_settings (branch_id, business_id)
  values (new.id, new.business_id) on conflict do nothing;
  return new;
end $$;
revoke all on function public.create_default_notification_settings() from public, anon, authenticated;
create trigger branches_create_notification_settings after insert on public.branches
  for each row execute function public.create_default_notification_settings();

insert into public.notification_settings (branch_id, business_id)
select b.id, b.business_id from public.branches b on conflict do nothing;

alter table public.notification_settings enable row level security;
create policy notification_settings_select on public.notification_settings
  for select to authenticated using (public.is_member(business_id));
create policy notification_settings_update on public.notification_settings
  for update to authenticated
  using (public.can(business_id, branch_id, 'settings.booking'))
  with check (public.can(business_id, branch_id, 'settings.booking'));
grant select, update on public.notification_settings to authenticated;
grant all on public.notification_settings to service_role;

