/**
 * Generates src/config/localeData.generated.ts from Node's ICU data.
 *
 * Why generated and not computed at runtime: Hermes (our native JS engine) has
 * no `Intl.supportedValuesOf` and no `Intl.Locale`, so the app cannot build
 * these lists on device. Node has full ICU, so we snapshot them here.
 *
 * Re-run after a Node/ICU upgrade:  node scripts/generate-locale-data.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const regionNames = new Intl.DisplayNames(['en'], { type: 'region' });
const currencyNames = new Intl.DisplayNames(['en'], { type: 'currency' });

/** Every ISO 3166-1 alpha-2 code ICU can name. */
function allCountries() {
  const out = [];
  for (let a = 65; a <= 90; a += 1) {
    for (let b = 65; b <= 90; b += 1) {
      const code = String.fromCharCode(a) + String.fromCharCode(b);
      let name;
      try {
        name = regionNames.of(code);
      } catch {
        continue;
      }
      // ICU echoes the code back when it does not know the region.
      if (name && name !== code) out.push({ code, name });
    }
  }
  return out.sort((x, y) => x.name.localeCompare(y.name, 'en'));
}

function allCurrencies() {
  return Intl.supportedValuesOf('currency')
    .map((code) => {
      let name = code;
      try {
        name = currencyNames.of(code) ?? code;
      } catch {
        /* keep the code */
      }
      return { code, name };
    })
    .sort((x, y) => x.code.localeCompare(y.code, 'en'));
}

function allTimezones() {
  // Drop deprecated aliases like "US/Pacific"; keep canonical Area/Location ids.
  return Intl.supportedValuesOf('timeZone')
    .filter((zone) => !/^(US|Canada|Mexico|Brazil|Chile|Etc)\//.test(zone))
    .sort((x, y) => x.localeCompare(y, 'en'));
}

const countries = allCountries();
const currencies = allCurrencies();
const timezones = allTimezones();

const file = `// GENERATED by scripts/generate-locale-data.mjs — do not edit by hand.
//
// Hermes has no Intl.supportedValuesOf and no Intl.Locale, so these lists
// cannot be built on device. They are snapshotted from Node's ICU data.
// Re-run the script after a Node upgrade to refresh them.

export type CountryOption = { code: string; name: string };
export type CurrencyOption = { code: string; name: string };

/** Every ISO 3166-1 alpha-2 country, by English name. */
export const allCountries: readonly CountryOption[] = ${JSON.stringify(countries, null, 2)};

/** Every ISO 4217 currency ICU knows. */
export const allCurrencies: readonly CurrencyOption[] = ${JSON.stringify(currencies, null, 2)};

/** Every canonical IANA timezone. */
export const allTimezones: readonly string[] = ${JSON.stringify(timezones, null, 2)};
`;

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(resolve(root, 'src/config/localeData.generated.ts'), file);

console.log(
  `generated: ${countries.length} countries, ${currencies.length} currencies, ${timezones.length} timezones`,
);
